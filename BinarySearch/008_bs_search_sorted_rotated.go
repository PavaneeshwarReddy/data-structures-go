package binarysearch

/*
Search in a sorted array

- There are chances that if left is unsorted then right is sorted and vice versa
- We need to decide which part of array is sorted and if it's sorted will our target can contain in that sorted if not go to other half

*/

func searchSorted(nums []int, target int) int {
	left := 0
	right := len(nums) - 1

	for left <= right {
		mid := (left + right) / 2
		if nums[mid] == target {
			return mid
		}

		if nums[left] <= nums[mid] {
			if nums[left] <= target && target < nums[mid] {
				right = mid - 1
			} else {
				left = mid + 1
			}
		} else {
			if nums[mid] < target && target <= nums[right] {
				left = mid + 1
			} else {
				right = mid - 1
			}
		}
	}

	return -1
}
